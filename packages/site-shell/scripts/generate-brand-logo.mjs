import { mkdir, readFile, writeFile } from "node:fs/promises"
import { dirname, resolve } from "node:path"
import { fileURLToPath } from "node:url"

const packageRoot = resolve(dirname(fileURLToPath(import.meta.url)), "..")
const sourceLogoPath = resolve(packageRoot, "../../apps/www/public/favicon/android-chrome-192x192.png")
const outputPath = resolve(packageRoot, "src/generated/brandLogo.ts")

async function main() {
	const logoBuffer = await readFile(sourceLogoPath)
	const dataUrl = `data:image/png;base64,${logoBuffer.toString("base64")}`

	const fileContents = `// This file is generated by scripts/generate-brand-logo.mjs.
// Source: apps/www/public/favicon/android-chrome-192x192.png

export const BRAND_LOGO_DATA_URL = ${JSON.stringify(dataUrl)}
`

	await mkdir(resolve(packageRoot, "src/generated"), { recursive: true })
	await writeFile(outputPath, fileContents)
	console.log(`[site-shell] generated ${outputPath}`)
}

main().catch((error) => {
	console.error("[site-shell] failed to generate the bundled brand logo asset", error)
	process.exit(1)
})
